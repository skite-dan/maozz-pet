// 预编译 IP 前缀匹配正则（/24 网段）
function buildCloudIPPattern() {
  var unique = [];
  var seen = {};
  for (var i = 0; i < CLOUD_IP_PREFIXES.length; i++) {
    var prefix = CLOUD_IP_PREFIXES[i];
    if (!seen[prefix]) {
      seen[prefix] = true;
      unique.push(prefix.replace('.', '\\.'));
    }
  }
  return new RegExp('^(?:' + unique.join('|') + ')');
}

var CLOUD_IP_REGEX = buildCloudIPPattern();

/**
 * 判断请求是否来自爬虫/云服务器
 * @param {Object} req - Express 请求对象
 * @returns {boolean} true 表示是爬虫/云服务器
 */
function isBotRequest(req) {
  var ua = (req.headers['user-agent'] || '').toLowerCase();
  var ip = req.ip || req.headers['x-forwarded-for'] || 'unknown';

  // 1. 检查 User-Agent 是否包含爬虫关键词
  for (var i = 0; i < BOT_UA_KEYWORDS.length; i++) {
    if (ua.indexOf(BOT_UA_KEYWORDS[i]) !== -1) {
      return true;
    }
  }

  // 2. 检查 IP 是否在云服务器/CDN 网段
  if (CLOUD_IP_REGEX.test(ip)) {
    return true;
  }

  // 3. 内网 IP 不统计
  if (ip === 'unknown' || ip === '127.0.0.1' || ip === '::1' || ip.startsWith('10.') || ip.startsWith('192.168.') || ip.startsWith('172.16.') || ip.startsWith('172.17.')) {
    return true;
  }

  return false;
}

